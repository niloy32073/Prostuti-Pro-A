/**
 * Prostuti's Material 3 theme. No dynamic (wallpaper-derived) color: the brand palette is a
 * deliberately fixed, reviewed system (brand red as `primary` in every theme), not something a
 * user's wallpaper should override.
 */
@Composable
fun ProstutiTheme(
    darkTheme: Boolean = androidx.compose.foundation.isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme
    val extendedColors = if (darkTheme) DarkExtendedColors else LightExtendedColors

    CompositionLocalProvider(LocalExtendedColors provides extendedColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = ProstutiMaterialTypography,
            shapes = ProstutiShapes,
            content = content
        )
    }
}

/** `success`/`onSuccess`/`successContainer`/`onSuccessContainer` for the current theme. */
val MaterialTheme.extendedColors: ExtendedColors
    @Composable
    get() = LocalExtendedColors.current
